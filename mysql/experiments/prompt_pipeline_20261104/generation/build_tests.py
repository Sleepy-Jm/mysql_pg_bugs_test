def write(path, text):
    dest = ROOT / path
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes((text.strip() + "\n").encode("utf-8"))


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2)


def case_sql(label, query):
    return f"\n-- CASE {label}\nSELECT '{label}' AS case_id;\n{query.strip().rstrip(';')};\n"


def response(name, sql, cases, prerequisites, oracle, coverage):
    write(f"sql/{name}.sql", sql)
    write(f"expected/{name}.json", json_text({
        "target": name,
        "row_order": "significant; each data SELECT orders by stable keys",
        "result_protocol": "A one-row case_id result identifies the next data result set. Environment metadata is not a test result. Case labels must be present in the specified order; omitted/error results cannot pass.",
        "null_encoding": "JSON null means SQL NULL, never zero or an empty string",
        "cases": cases,
    }))
    table = "\n".join(f"{c['case_id']}: columns={c['columns']}; expected={json.dumps(c['rows'], ensure_ascii=False)}" for c in cases)
    body = (f"Prerequisites\n{prerequisites}\n\nSQL\n```sql\n{sql.strip()}\n```\n\n"
            f"Expected results and oracle\n{oracle}\n\n{table}\n\n"
            f"Coverage observation\n{coverage}\n\nExecution status\n"
            "Generated by the current assistant from the saved req2test prompt and its new src2req requirements. "
            "No database was connected, SQL executed, or source coverage measured. Expected rows are semantic calculations, not observed results. "
            "Retain SQL errors/crashes/missing results as separate observations; do not silently treat them as correct or as confirmed bugs.")
    write(f"stage2_req2test/responses/{name}.txt", body)


def charset_cases():
    name = TARGETS[0]
    sql = """-- UTF-8 file. Run in a fresh session with a selected disposable schema.
-- Target: 4d2da251cb536340d19438cc0039bb2846f9a634.
-- wf_4d2_text must not already exist. No pre-test DROP of unknown objects.
SELECT VERSION() AS server_version, DATABASE() AS test_schema,
       @@SESSION.optimizer_switch AS initial_optimizer_switch;
SET @wf_4d2_optimizer = @@SESSION.optimizer_switch;
SET @wf_4d2_client = @@SESSION.character_set_client;
SET @wf_4d2_results = @@SESSION.character_set_results;
SET @wf_4d2_collation = @@SESSION.collation_connection;
SET NAMES utf8mb4 COLLATE utf8mb4_bin;
CREATE TABLE wf_4d2_text (
  id INT PRIMARY KEY,
  s VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin
) ENGINE=InnoDB;
INSERT INTO wf_4d2_text VALUES (1,'a'),(2,'b'),(3,''),(4,'a'),(5,NULL);
"""
    specs = [
        ("DCP01", "'é'", "é", "implicit_utf8mb4"),
        ("DCP02", "_utf8mb4'é'", "é", "explicit_utf8mb4"),
        ("DCP03", "_utf8mb4'中'", "中", "explicit_multibyte"),
        ("DCP04", "_utf8mb4'O''Reilly'", "O'Reilly", "embedded_quote"),
    ]
    cases = []
    for prefix, literal, suffix, variant in specs:
        tag = "a" + suffix
        predicate = "_utf8mb4'" + tag.replace("'", "''") + "' COLLATE utf8mb4_bin"
        query = f"""SELECT d.id, HEX(d.tag) AS tag_hex,
       CHAR_LENGTH(d.tag) AS char_len, OCTET_LENGTH(d.tag) AS byte_len
FROM (
  SELECT DISTINCT id, CONCAT(s, {literal}) AS tag
  FROM wf_4d2_text
) AS d
WHERE d.tag = {predicate}
ORDER BY d.id"""
        for mode in ("off", "on"):
            sql += f"\nSET SESSION optimizer_switch = 'derived_condition_pushdown={mode}';\n"
            label = f"{prefix}_{mode.upper()}"
            sql += case_sql(label, query)
            cases.append({"case_id": label, "family": variant, "pushdown": mode,
                          "columns": ["id", "tag_hex", "char_len", "byte_len"],
                          "comparison": "exact",
                          "rows": [[i, tag.encode('utf-8').hex().upper(), len(tag), len(tag.encode('utf-8'))] for i in (1,4)]})
    sql += """
-- Cleanup and session restoration after all data results.
DROP TABLE wf_4d2_text;
SET SESSION optimizer_switch = @wf_4d2_optimizer;
SET SESSION character_set_client = @wf_4d2_client;
SET SESSION character_set_results = @wf_4d2_results;
SET SESSION collation_connection = @wf_4d2_collation;
"""
    response(name, sql, cases,
             "Use a MySQL build supporting derived_condition_pushdown, utf8mb4 and utf8mb4_bin; bind source coverage to the target SHA, not an assumed release label. Use a fresh session and an already selected disposable schema with CREATE/DROP privileges. The ordinary table wf_4d2_text must not exist. Read this file as UTF-8; it contains real é and 中 literals. The script saves/restores its optimizer and connection-character-set settings on normal completion. If it aborts, retain diagnostics, close the session and drop only this run's table after confirming it was created by this run.",
             "Each suffix matches exactly ids 1 and 4, whose input s is 'a'. DISTINCT includes id, so these two rows remain distinct. Compute UTF-8 bytes directly from 'a'+suffix: 61C3A9; 61E4B8AD; or 614F275265696C6C79. Character/byte lengths are 2/3, 2/4, or 9/9. NULL fails equality. Each OFF and ON result must match the independently specified rows, not merely match one another.",
             "For each ON case, identify the materialized derived table and trace sql/item.cc:1051-1055 to sql/sql_derived.cc:734-744 and parse_expression:550-575,617-635. Record Item_string::print at sql/item.cc:3433-3472: introducer decision, literal collation, QT_TO_ARGUMENT_CHARSET, destination StringBuffer charset, serialized bytes and reparse result. Inspect that the implicit and explicit cases take their intended branches. OFF is a path control; it is not a correctness authority. No runtime path is asserted by this generated response.")


def property_cases():
    name = TARGETS[1]
    sql = """-- Target: 248c7f7c227e76f3422378ca3b9e10d141dcfc86.
-- Fresh session, selected disposable schema, unique temporary-table/statement names.
SELECT VERSION() AS server_version, DATABASE() AS test_schema;
CREATE TEMPORARY TABLE wf_248_values (g INT, id INT, v INT, PRIMARY KEY (g,id));
CREATE TEMPORARY TABLE wf_248_lookup (k INT);
INSERT INTO wf_248_values VALUES
 (1,1,10),(1,2,NULL),(1,3,30),(1,4,40),(2,1,NULL),(2,2,NULL);
INSERT INTO wf_248_lookup VALUES (11),(71),(NULL);
"""
    wrapped = """SELECT g, id, ? + SUM(v) OVER w AS wrapped,
       ROW_NUMBER() OVER (PARTITION BY g ORDER BY id DESC) AS rn_rev
FROM wf_248_values
WINDOW w AS (PARTITION BY g ORDER BY id ROWS BETWEEN CURRENT ROW AND 1 FOLLOWING)
ORDER BY g,id"""
    sql += "\nPREPARE wf_248_a FROM '" + wrapped.replace("'", "''") + "';\n"
    cases = []
    def rows_for(offset):
        return [[1, i+1, s+offset, 4-i] for i,s in enumerate([10,30,70,40])] + [[2,1,None,2],[2,2,None,1]]
    for label,offset in [("PROP_A1_PREPARED",1),("PROP_A2_REPEAT",1),("PROP_A3_OFFSET",11)]:
        sql += f"\nSET @wf_248_offset = {offset};\n"
        sql += case_sql(label, "EXECUTE wf_248_a USING @wf_248_offset")
        cases.append({"case_id": label, "family": "wrapped_window_reuse", "offset": offset,
                      "columns": ["g","id","wrapped","rn_rev"], "comparison": "numeric_exact",
                      "rows": rows_for(offset)})
