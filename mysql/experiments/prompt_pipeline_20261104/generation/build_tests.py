WINDOW_DATA = [(1,1,10),(1,2,20),(1,3,30),(1,4,40),
               (2,1,None),(2,2,20),(2,3,None),(2,4,60),
               (3,1,None),(3,2,None),(4,1,7)]


def window_rows(frame, with_values=False):
    grouped = defaultdict(list)
    for g,i,v in WINDOW_DATA:
        grouped[g].append((i,v))
    output = []
    for g, rows in sorted(grouped.items()):
        for pos,(i,_) in enumerate(rows):
            if frame == "following":
                members = rows[pos+1:]
            elif frame == "current":
                members = rows[pos:]
            elif frame == "bounded":
                members = rows[max(0,pos-1):pos+2]
            elif frame == "cumulative":
                members = rows[:pos+1]
            else:
                raise ValueError(frame)
            values = [v for _,v in members if v is not None]
            avg = None if not values else str((Decimal(sum(values))/len(values)).quantize(Decimal("0.000001"), rounding=ROUND_HALF_UP))
            row = [g,i,avg]
            if with_values:
                row += [members[0][1] if members else None,
                        members[-1][1] if members else None,
                        members[1][1] if len(members)>1 else None]
            output.append(row)
    return output


def window_cases():
    name = TARGETS[2]
    sql = """-- Target: c296cddb93ffc631f9b43d3b1ff769604e7469d7.
-- Source coverage is tied to this SHA; later releases may contain fixes.
SELECT VERSION() AS server_version, DATABASE() AS test_schema,
       @@SESSION.windowing_use_high_precision AS initial_high_precision;
SET @wf_c296_precision = @@SESSION.windowing_use_high_precision;
CREATE TEMPORARY TABLE wf_c296_values (
  g INT, id INT, v_dec DECIMAL(12,2), v_real DOUBLE, PRIMARY KEY (g,id)
);
INSERT INTO wf_c296_values VALUES
"""
    sql += ",\n".join(f" ({g},{i},{'NULL' if v is None else v},{'NULL' if v is None else v})" for g,i,v in WINDOW_DATA) + ";\n"
    specs = [
        ("WIN01_DEC_FORWARD","following","v_dec","OFF",False),
        ("WIN02_REAL_FORWARD_INVERSE","following","v_real","OFF",False),
        ("WIN03_REAL_FORWARD_PRECISE","following","v_real","ON",False),
        ("WIN04_DEC_CURRENT","current","v_dec","OFF",False),
        ("WIN05_REAL_CURRENT","current","v_real","OFF",False),
        ("WIN06_DEC_BOUNDED","bounded","v_dec","OFF",False),
        ("WIN07_REAL_BOUNDED","bounded","v_real","OFF",False),
        ("WIN08_DEC_CUMULATIVE_CONTROL","cumulative","v_dec","OFF",False),
        ("WIN09_VALUE_FUNCTIONS","following","v_dec","OFF",True),
    ]
    frames = {"following":"1 FOLLOWING AND UNBOUNDED FOLLOWING",
              "current":"CURRENT ROW AND UNBOUNDED FOLLOWING",
              "bounded":"1 PRECEDING AND 1 FOLLOWING",
              "cumulative":"UNBOUNDED PRECEDING AND CURRENT ROW"}
    cases = []
    for label,frame,column,precision,extra in specs:
        sql += f"\nSET SESSION windowing_use_high_precision = {precision};\n"
        select = f"SELECT g,id,CAST(AVG({column}) OVER w AS DECIMAL(20,6)) AS avg_v"
        if extra:
            select += ",\n       FIRST_VALUE(v_dec) OVER w AS first_v,\n       LAST_VALUE(v_dec) OVER w AS last_v,\n       NTH_VALUE(v_dec,2) OVER w AS second_v"
        query = select + f"\nFROM wf_c296_values\nWINDOW w AS (PARTITION BY g ORDER BY id ROWS BETWEEN {frames[frame]})\nORDER BY g,id"
        sql += case_sql(label,query)
        cases.append({"case_id":label,"family":frame,"input_type":column,"high_precision":precision,
                      "columns":["g","id","avg_v"]+(["first_v","last_v","second_v"] if extra else []),
                      "comparison":"numeric_exact" if column=="v_dec" else "numeric_absolute_tolerance",
                      "absolute_tolerance":"0" if column=="v_dec" else "0.000001",
                      "rows":window_rows(frame,extra)})
    sql += "\nDROP TEMPORARY TABLE wf_c296_values;\nSET SESSION windowing_use_high_precision = @wf_c296_precision;\n"
    response(name, sql, cases,
             "Use a MySQL build supporting the named window syntax, window AVG/FIRST_VALUE/LAST_VALUE/NTH_VALUE and windowing_use_high_precision. Bind coverage to c296cddb93ffc631f9b43d3b1ff769604e7469d7 and the saved parent if attribution is later attempted. Use one fresh session and a selected disposable schema; wf_c296_values must not exist. All values are small exactly representable integer inputs; decimal and real columns contain the same values. The script restores the precision setting on normal completion; close the session on an abort after saving diagnostics.",
             "Enumerate the frame for each (g,id), discard NULL only for AVG, and divide sum by the count of remaining values. Format AVG through the explicit DECIMAL(20,6) output cast. Decimal expected strings are exact six-place rounded semantic results; compare numeric values rather than textual trailing-zero formatting. For REAL only, permit absolute error <=0.000001 after the cast. All NULL positions must match exactly. FIRST/LAST/NTH use frame-row positions and retain NULLs. For group 1, forward means are 30,35,40,NULL; current means 25,30,35,40; bounded means 15,20,30,35. The all-NULL and singleton groups test different boundaries. The ON query and cumulative query are controls, not trusted-answer generators.",
             "Observe optimized ROWS strategy and priming at sql/iterators/window_iterators.cc:1092, the removal/no-new-last-row guards at 1098-1107, inverse and position state at 1150-1156, and the AVG buffered divisors at sql/item_sum.cc:2286-2290,2350-2357. Correlate window/object/output-row identity, lower_limit, current_row, rows_in_frame, rowno_in_frame, m_count, m_frame_null_count and is_last_row_in_frame. Trace the additional 1174/1190/1207 setters in WIN09 and 1220 for bounded frames separately. WIN02 is the intended REAL inverse candidate; WIN03 enables high precision. The displayed source formula can assign zero with a 1 FOLLOWING lower border, but these scripts do not claim the runtime guards were reached.")


def main():
    charset_cases()
    property_cases()
    window_cases()
    manifest_path = ROOT / "generation_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    for record in manifest["targets"]:
        name = record["target"]
        for key,path in {
            "req2test_output":f"stage2_req2test/responses/{name}.txt",
            "sql":f"sql/{name}.sql",
            "expected":f"expected/{name}.json",
        }.items():
            record[key] = path
            record[f"{key}_sha256"] = hashlib.sha256((ROOT/path).read_bytes()).hexdigest()
        record["case_count"] = len(json.loads((ROOT/record["expected"]).read_text(encoding="utf-8"))["cases"])
    manifest_path.write_text(json_text(manifest) + "\n", encoding="utf-8")
    print("Generated 3 SQL scripts, 25 labelled data results, 3 complete req2test responses and expected rows")


if __name__ == "__main__":
    main()
