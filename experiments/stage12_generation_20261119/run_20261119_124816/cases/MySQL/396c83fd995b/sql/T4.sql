-- 准备
DROP TABLE IF EXISTS t4;
CREATE TABLE t4 (id INT PRIMARY KEY, g INT NOT NULL, v INT NOT NULL);
INSERT INTO t4 VALUES (1,1,10),(2,1,20),(3,2,30),(4,2,40),(5,3,50);

-- 目标 SELECT：别名 s 同时被 GROUP BY 和 HAVING 引用
SELECT g, SUM(v) AS s
FROM t4
GROUP BY g
HAVING s > 25
ORDER BY g;

-- 对照：不使用别名
SELECT g, SUM(v) AS s
FROM t4
GROUP BY g
HAVING SUM(v) > 25
ORDER BY g;

-- 清理
DROP TABLE IF EXISTS t4;
