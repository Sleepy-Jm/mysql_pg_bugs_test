-- 准备：创建表并插入 INTEGER 与 REAL 混合值
CREATE TABLE t4(i INTEGER, r REAL);
INSERT INTO t4 VALUES
  (9223372036854775807, 9.223372036854775808e+18),  -- i = 2^63-1, r = 2^63
  (9223372036854775807, 9.223372036854775807e+18),  -- r 略小于 2^63
  (-9223372036854775808, -9.223372036854775808e+18),-- i = -2^63, r = -2^63
  (9007199254740993, 9007199254740992.0),           -- i = 2^53+1, r = 2^53
  (9007199254740993, 9007199254740994.0);           -- i = 2^53+1, r = 2^53+2
-- 目标：观察 INTEGER 与 REAL 比较结果
SELECT i, r,
       (i < r) AS lt,
       (i = r) AS eq,
       (i > r) AS gt
FROM t4
ORDER BY i, r;
-- 清理
DROP TABLE t4;
