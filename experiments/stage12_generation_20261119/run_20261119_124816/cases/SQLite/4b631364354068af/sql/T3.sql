-- 准备
CREATE TABLE p(x INTEGER);
CREATE TABLE q(x INTEGER);
INSERT INTO p VALUES (1),(2),(3),(4),(5);
INSERT INTO q VALUES (90),(80),(70);

-- 目标 SELECT：左臂 5 行，LIMIT+OFFSET=3，左臂已吃完
SELECT x FROM p
UNION ALL
SELECT x FROM (SELECT x FROM q ORDER BY x DESC)
LIMIT 2 OFFSET 1;

-- 对照：等价显式拼接
SELECT x FROM (
  SELECT x FROM p
  UNION ALL
  SELECT x FROM (SELECT x FROM q ORDER BY x DESC)
) LIMIT 2 OFFSET 1;

-- 清理
DROP TABLE p;
DROP TABLE q;
