-- 准备
CREATE TABLE u(x INTEGER);
CREATE TABLE v(x INTEGER);
INSERT INTO u VALUES (7),(8);
INSERT INTO v VALUES (60),(50),(40);

-- 目标 SELECT：OFFSET 0，右臂带 ORDER BY
SELECT x FROM u
UNION ALL
SELECT x FROM (SELECT x FROM v ORDER BY x DESC)
LIMIT 2 OFFSET 0;

-- 对照：等价显式拼接
SELECT x FROM (
  SELECT x FROM u
  UNION ALL
  SELECT x FROM (SELECT x FROM v ORDER BY x DESC)
) LIMIT 2 OFFSET 0;

-- 清理
DROP TABLE u;
DROP TABLE v;
