-- 准备
CREATE TABLE a(x INTEGER);
CREATE TABLE b(x INTEGER);
INSERT INTO a VALUES (1),(2),(3);
INSERT INTO b VALUES (100),(200),(300);

-- 目标 SELECT：左臂 3 行，OFFSET=3 恰好被左臂吃完
SELECT x FROM a
UNION ALL
SELECT x FROM (SELECT x FROM b ORDER BY x DESC)
LIMIT 2 OFFSET 3;

-- 对照：等价显式拼接
SELECT x FROM (
  SELECT x FROM a
  UNION ALL
  SELECT x FROM (SELECT x FROM b ORDER BY x DESC)
) LIMIT 2 OFFSET 3;

-- 清理
DROP TABLE a;
DROP TABLE b;
